#!/bin/bash
#
# Flags-drift check: hold the compile and link flags of the maixlite build of kvm_system to
# the ones MaixCDK's CMake generated (tools/binabi/golden/kvm_system.flags, taken from the
# 2.6.39 evidence bundle). Every flags.make (defines, include order, flags) and link.txt
# (archive members, link line) is compared, literally, after the path normalisation below.
#
# Usage:
#   tools/binabi/flags.sh <build-dir> <maixlite-src-dir> <nanokvm-dir>
#       compare the CMake build tree of maixlite to the golden; fails on any difference
#   tools/binabi/flags.sh --extract <dir> <maixlite-src-dir> <nanokvm-dir>
#       print the normalised form of <dir>: a CMake build tree, or an evidence
#       flags/<project> directory (files named <dir>%CMakeFiles%...%flags.make)
#
# Normalisation (so a MaixCDK tree and a maixlite tree compare): the source roots become
# @MAIXLITE@ (MaixCDK's @MAIXCDK@ is mapped to it: maixlite keeps MaixCDK's components/
# layout), the generated-config include directory becomes @CONFIG@ (MaixCDK's
# kvm_system/build/config; maixlite's config/), and an object path that CMake spells
# through "__/" because its source sits outside the target's directory (kvm_system/main,
# additional/peripheral) is spelled as it was inside MaixCDK's component. CMake's
# "generated by" comment lines are dropped. Nothing else is touched: a flag that differs
# is a difference.

set -u
set -o pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
GOLDEN="${BINABI_FLAGS_GOLDEN:-$HERE/golden/kvm_system.flags}"

die() {
    echo "[flags] ERROR: $*" >&2
    exit 1
}

extract() { # extract <dir> <maixlite-src> <nanokvm>
    local dir="$1" lite="$2" nano="$3" rel name f
    [ -d "$dir" ] || die "$dir is not a directory"
    local names
    # sorted by the flattened name, so a build tree and an evidence directory list alike
    names="$(cd "$dir" && find . -type f \( -name '*flags.make' -o -name '*link.txt' \) \
        | sed -e 's#^\./##' -e 's#^\(.*\)$#\1\t\1#' | awk -F'\t' '{ n = $1; gsub("/", "%", n); print n "\t" $2 }' \
        | LC_ALL=C sort | cut -f2)" \
        || die "find failed in $dir"
    [ -n "$names" ] || die "no flags.make or link.txt under $dir"
    while IFS= read -r rel; do
        name="$(printf '%s' "$rel" | tr '/' '%')"
        f="$dir/$rel"
        printf '=== %s\n' "$name"
        sed -e '/^# CMAKE generated file/d' -e '/^# Generated by/d' \
            -e "s#$lite/config#@CONFIG@#g" \
            -e "s#$lite#@MAIXLITE@#g" \
            -e "s#$nano#@NANOKVM@#g" \
            -e 's#@NANOKVM@/support/sg2002/kvm_system/build/config#@CONFIG@#g' \
            -e 's#@MAIXCDK@#@MAIXLITE@#g' \
            -e 's#\.dir/\(__/\)\{1,\}kvm_system/main/#.dir/#g' \
            -e 's#\.dir/\(__/\)\{1,\}additional/peripheral/#.dir/#g' \
            "$f" || die "sed failed on $f"
    done <<< "$names"
}

if [ "${1:-}" = "--extract" ]; then
    [ $# -eq 4 ] || die "usage: $0 --extract <dir> <maixlite-src-dir> <nanokvm-dir>"
    extract "$2" "$3" "$4"
    exit $?
fi

[ $# -eq 3 ] || die "usage: $0 <build-dir> <maixlite-src-dir> <nanokvm-dir> | --extract <dir> <maixlite-src-dir> <nanokvm-dir>"
[ -s "$GOLDEN" ] || die "$GOLDEN is missing or empty"
tmp="$(mktemp)" || die "mktemp failed"
extract "$1" "$2" "$3" > "$tmp" || { rm -f "$tmp"; die "could not extract the flags of $1"; }
[ -s "$tmp" ] || { rm -f "$tmp"; die "extracted nothing from $1"; }
if diff -u "$GOLDEN" "$tmp"; then
    echo "[flags] kvm_system compile and link flags match the MaixCDK golden ($(grep -c '^=== ' "$tmp") files)"
    rm -f "$tmp"
    exit 0
fi
rm -f "$tmp"
die "kvm_system flags differ from the MaixCDK golden (diff above; golden = $GOLDEN)"
