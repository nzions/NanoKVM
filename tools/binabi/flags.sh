#!/bin/bash
#
# Flags-drift check: hold the compile and link flags of the maixlite builds to the ones
# MaixCDK's CMake generated: kvm_system (tools/binabi/golden/kvm_system.flags, taken from
# the 2.6.39 evidence bundle) and kvm_vision_test, the project libkvm.so and libkvm_mmf.so
# were built in (golden/kvm_vision_test.flags, from the 2.6.41 evidence bundle). Every
# flags.make (defines, include order, flags) and link.txt (archive members, link line) is
# compared, literally, after the path normalisation below.
#
# Usage:
#   tools/binabi/flags.sh <build-dir> <maixlite-src-dir> <nanokvm-dir> [project]
#       compare the CMake build tree of maixlite to the golden; fails on any difference.
#       project: kvm_system (default) or kvm_vision_test
#   tools/binabi/flags.sh --extract <dir> <maixlite-src-dir> <nanokvm-dir> [project]
#       print the normalised form of <dir>: a CMake build tree, or an evidence
#       flags/<project> directory (files named <dir>%CMakeFiles%...%flags.make)
#
# Normalisation (so a MaixCDK tree and a maixlite tree compare): the source roots become
# @MAIXLITE@ (MaixCDK's @MAIXCDK@ is mapped to it: maixlite keeps MaixCDK's components/
# layout), the generated-config include directory becomes @CONFIG@ (MaixCDK's
# <project>/build/config; maixlite's config/ or config-kvm_vision_test/), and an object path
# that CMake spells with the source's absolute path because the source sits outside the
# target's directory (kvm_system/main, additional/peripheral) is spelled as it was inside
# MaixCDK's component (CMakeFiles/main.dir/src/main.cpp.o). CMake's "generated by" comment
# lines are dropped. Nothing else is touched: a flag that differs is a difference.
#
# kvm_vision_test only:
#  * additional/{kvm,kvm_mmf,vision} (our components, which MaixCDK copied into its
#    components/) are spelled @MAIXLITE@/components/<name>, as MaixCDK's were;
#  * the pinned middleware tree and the MMF output tree (NANOKVM_MIDDLEWARE_SRC,
#    NANOKVM_MMF_LIB's parent: set in the environment when a build tree is compared) become
#    @MIDDLEWARE@ and @MMF_OUT@, as the evidence bundle spelled them;
#  * the carrier executable (kvm_vision_test, its main component) is not part of the golden:
#    maixlite builds the two libraries only;
#  * THE ONE ACCEPTED DIFFERENCE: the build-tree rpath option MaixCDK's libkvm.so link line
#    carried (-Wl,-rpath,<build dir>/kvm_mmf, the leak S6 removed) is deleted from the
#    golden's side. A build that still had it would fail tools/binabi's rpath check.

set -u
set -o pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"

die() {
    echo "[flags] ERROR: $*" >&2
    exit 1
}

extract() { # extract <dir> <maixlite-src> <nanokvm> <project>
    local dir="$1" lite="$2" nano="$3" project="$4" rel name f
    [ -d "$dir" ] || die "$dir is not a directory"
    local names
    # sorted by the flattened name, so a build tree and an evidence directory list alike
    names="$(cd "$dir" && find . -type f \( -name '*flags.make' -o -name '*link.txt' \) \
        | sed -e 's#^\./##' -e 's#^\(.*\)$#\1\t\1#' | awk -F'\t' '{ n = $1; gsub("/", "%", n); print n "\t" $2 }' \
        | LC_ALL=C sort | cut -f2)" \
        || die "find failed in $dir"
    [ -n "$names" ] || die "no flags.make or link.txt under $dir"
    local -a extra=()
    if [ "$project" = kvm_vision_test ]; then
        # our components, spelled as they were inside MaixCDK's components/
        extra+=(-e 's#\.dir@NANOKVM@/support/sg2002/additional/\(kvm_mmf\|kvm\|vision\)/#.dir/#g')
        extra+=(-e 's#@NANOKVM@/support/sg2002/additional/\(kvm_mmf\|kvm\|vision\)\([/ ]\|$\)#@MAIXLITE@/components/\1\2#g')
        extra+=(-e 's# -Wl,-rpath,@NANOKVM@/support/sg2002/kvm_vision_test/build/kvm_mmf##')
        if [ -n "${NANOKVM_MIDDLEWARE_SRC:-}" ]; then
            extra+=(-e "s#$NANOKVM_MIDDLEWARE_SRC#@MIDDLEWARE@#g")
        fi
        if [ -n "${NANOKVM_MMF_LIB:-}" ]; then
            extra+=(-e "s#${NANOKVM_MMF_LIB%/lib}#@MMF_OUT@#g")
        fi
    fi
    while IFS= read -r rel; do
        name="$(printf '%s' "$rel" | tr '/' '%')"
        if [ "$project" = kvm_vision_test ]; then
            case "$name" in
                CMakeFiles%kvm_vision_test.dir%*|main%CMakeFiles%main.dir%*) continue ;;
            esac
        fi
        f="$dir/$rel"
        printf '=== %s\n' "$name"
        sed -e '/^# CMAKE generated file/d' -e '/^# Generated by/d' \
            -e "s#$lite/config-kvm_vision_test#@CONFIG@#g" \
            -e "s#$lite/config#@CONFIG@#g" \
            -e "s#$lite#@MAIXLITE@#g" \
            -e "s#$nano#@NANOKVM@#g" \
            -e 's#@NANOKVM@/support/sg2002/kvm_system/build/config#@CONFIG@#g' \
            -e 's#@NANOKVM@/support/sg2002/kvm_vision_test/build/config#@CONFIG@#g' \
            -e 's#@MAIXCDK@#@MAIXLITE@#g' \
            -e 's#\.dir@NANOKVM@/support/sg2002/kvm_system/main/#.dir/#g' \
            -e 's#\.dir@NANOKVM@/support/sg2002/additional/peripheral/#.dir/#g' \
            "${extra[@]}" \
            "$f" || die "sed failed on $f"
    done <<< "$names"
}

check_project() {
    case "$1" in
        kvm_system|kvm_vision_test) ;;
        *) die "unknown project '$1' (kvm_system or kvm_vision_test)" ;;
    esac
}

if [ "${1:-}" = "--extract" ]; then
    [ $# -eq 4 ] || [ $# -eq 5 ] || die "usage: $0 --extract <dir> <maixlite-src-dir> <nanokvm-dir> [project]"
    check_project "${5:-kvm_system}"
    extract "$2" "$3" "$4" "${5:-kvm_system}"
    exit $?
fi

[ $# -eq 3 ] || [ $# -eq 4 ] || die "usage: $0 <build-dir> <maixlite-src-dir> <nanokvm-dir> [project] | --extract <dir> <maixlite-src-dir> <nanokvm-dir> [project]"
PROJECT="${4:-kvm_system}"
check_project "$PROJECT"
GOLDEN="${BINABI_FLAGS_GOLDEN:-$HERE/golden/$PROJECT.flags}"
if [ "$PROJECT" = kvm_vision_test ]; then
    [ -n "${NANOKVM_MIDDLEWARE_SRC:-}" ] && [ -n "${NANOKVM_MMF_LIB:-}" ] \
        || die "NANOKVM_MIDDLEWARE_SRC and NANOKVM_MMF_LIB must be set to compare a kvm_vision_test build tree"
fi
[ -s "$GOLDEN" ] || die "$GOLDEN is missing or empty"
tmp="$(mktemp)" || die "mktemp failed"
extract "$1" "$2" "$3" "$PROJECT" > "$tmp" || { rm -f "$tmp"; die "could not extract the flags of $1"; }
[ -s "$tmp" ] || { rm -f "$tmp"; die "extracted nothing from $1"; }
if diff -u "$GOLDEN" "$tmp"; then
    echo "[flags] $PROJECT compile and link flags match the MaixCDK golden ($(grep -c '^=== ' "$tmp") files)"
    rm -f "$tmp"
    exit 0
fi
rm -f "$tmp"
die "$PROJECT flags differ from the MaixCDK golden (diff above; golden = $GOLDEN)"
