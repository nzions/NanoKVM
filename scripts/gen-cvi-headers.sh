#!/bin/bash
#
# Generate the two header sets libcvi_bin is compiled against, from public sources.
#
# sophgo-middleware's libcvi_bin (v2/modules/bin) includes <cvi_json.h> and
# "cvi_miniz.h". Sophgo builds those from OSS tarballs (cvi-json-c, cvi-miniz) that are
# not in the middleware pin and have no source: they are upstream json-c and miniz
# with every public name given a cvi_ prefix. The libraries are NOT needed: libcvi_bin
# leaves every cvi_json_* / cvi_compress* symbol undefined, and the closed
# libcvi_bin_isp.so of the same pin (v2/modules/isp/lib/musl_riscv64) defines them
# (json-c and miniz are statically linked into it; build-mmf.sh checks this). So only
# the declarations are needed, and they are generated here:
#
#   <out>/include/cvi_json-c/cvi_*.h   json-c 0.15-20200726 headers, renamed by
#                                      mmf-shim/rename/json-c.sed (checked against
#                                      Sophgo's headers by diffing: struct layouts and
#                                      every function the blob exports are identical;
#                                      Sophgo's are a 0.15.99 snapshot)
#   <out>/include/cvi_miniz/cvi_miniz.h the three functions rw_json.c calls, with
#                                      miniz's signatures (mz_compress2, mz_compressBound,
#                                      mz_uncompress2, mz_ulong = unsigned long) renamed cvi_*
#
# Usage: gen-cvi-headers.sh <json-c source dir> <outdir>

set -euo pipefail
die() { echo "[gen-cvi-headers] ERROR: $*" >&2; exit 1; }

[ $# -eq 2 ] || die "usage: $0 <json-c source dir> <outdir>"
SRC="$1"; OUT="$2"
HERE="$(cd "$(dirname "$0")" && pwd)"
SED_RULES="$HERE/mmf-shim/rename/json-c.sed"
[ -f "$SRC/json_object.h" ] || die "$SRC is not a json-c source tree"
[ -f "$SED_RULES" ] || die "$SED_RULES is missing"

J="$OUT/include/cvi_json-c"
mkdir -p "$J" "$OUT/include/cvi_miniz"
for h in json json_c_version json_inttypes json_object json_object_iterator json_pointer \
         json_tokener json_types json_util json_visit arraylist debug linkhash printbuf; do
    [ -f "$SRC/$h.h" ] || die "$SRC/$h.h is missing"
    sed -f "$SED_RULES" "$SRC/$h.h" > "$J/cvi_$h.h"
done
# json_config.h is produced by cmake upstream; libcvi_bin's inttypes include needs only this.
printf '/* Define to 1 if you have the <inttypes.h> header file. */\n#define JSON_C_HAVE_INTTYPES_H 1\n' > "$J/cvi_json_config.h"

cat > "$OUT/include/cvi_miniz/cvi_miniz.h" <<'HDR'
/* Generated by scripts/gen-cvi-headers.sh: the part of miniz (public domain) that
 * sophgo-middleware's libcvi_bin calls, under the cvi_ names Sophgo's libcvi_bin_isp.so
 * exports. Signatures are miniz's mz_compress2 / mz_compressBound / mz_uncompress2. */
#ifndef CVI_MINIZ_SHIM_H
#define CVI_MINIZ_SHIM_H
#ifdef __cplusplus
extern "C" {
#endif
typedef unsigned long mz_ulong;
typedef unsigned char Byte;
typedef unsigned int uInt;
typedef mz_ulong uLong;
typedef Byte Bytef;
typedef uLong uLongf;
#define MZ_OK 0
#define MZ_DEFAULT_COMPRESSION (-1)
#define Z_OK MZ_OK
#define Z_DEFAULT_COMPRESSION MZ_DEFAULT_COMPRESSION
int cvi_compress2(unsigned char *pDest, mz_ulong *pDest_len, const unsigned char *pSource,
                  mz_ulong source_len, int level);
mz_ulong cvi_compressBound(mz_ulong source_len);
int cvi_uncompress2(unsigned char *pDest, mz_ulong *pDest_len, const unsigned char *pSource,
                    mz_ulong *pSource_len);
#ifdef __cplusplus
}
#endif
#endif
HDR
echo "[gen-cvi-headers] headers in $OUT/include"
